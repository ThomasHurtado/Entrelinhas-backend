export const INVALID_BIRTH_DATE = "Data de nascimento inválida.";

// Compare calendar dates directly; never parse a birth date into a timestamp.
export function isValidBirthDate(value, today = new Date().toISOString().slice(0, 10)) {
  if (value === null) return true;
  if (typeof value !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const [year, month, day] = value.split("-").map(Number);
  if (year < 1 || month < 1 || month > 12 || day < 1) return false;
  const leapYear = year % 4 === 0 && (year % 100 !== 0 || year % 400 === 0);
  const days = [31, leapYear ? 29 : 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
  return day <= days[month - 1] && value <= today;
}
